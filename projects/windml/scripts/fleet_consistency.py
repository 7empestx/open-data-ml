"""Compare `windml report` scorecards with the hand-built sample report (reports/condition_report/tables/scorecard.csv).
Writes reports/fleet_proof/consistency.md. Usage: python scripts/fleet_consistency.py [farm ...]"""
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
HAND = ROOT / "reports" / "condition_report" / "tables" / "scorecard.csv"
PAIRS = [("flag", "flag", "{}"), ("avail_time", "avail_time", "{:.1%}"), ("avail_energy", "avail_energy", "{:.1%}"),
         ("fault_h_per_yr", "fault_h_per_yr", "{:.0f}"), ("oil_ep_window", "oil_ep_window", "{:.0f}"),
         ("pitch_ep_window", "pitch_ep_window", "{:.0f}"), ("oil_abn_final_year", "abn_oil_final_year", "{:.1%}"),
         ("oil_temp_mae_ratio", "oil_temp_mae_ratio", "{:.2f}"), ("pump_rise_bar", "pump_rise", "{:+.2f}"),
         ("missing_window", "missing", "{:.1%}")]


def fmt(f, v):
    try:
        return f.format(v)
    except (ValueError, TypeError):
        return "-"


def main(farms):
    hand = pd.read_csv(HAND)
    L = ["# windml report vs the hand-built condition report", "",
         "Generated by `scripts/fleet_consistency.py`. Left value: hand-built report "
         "(`reports/condition_report`, scripts/condition_*.py); right value: `windml report` (`reports/<farm>/tables/scorecard.csv`).", ""]
    for farm in farms:
        new = pd.read_csv(ROOT / "reports" / farm / "tables" / "scorecard.csv")
        new["missing"] = 1 - new["coverage_window"]
        h = hand[hand["farm"] == farm].set_index("turbine_id")
        n = new.set_index("turbine_id")
        same = int((h["flag"] == n.loc[h.index, "flag"]).sum())
        L += [f"## {farm}: same flag for {same} of {len(h)} turbines", "",
              "| turbine | " + " | ".join(a for a, _, _ in PAIRS) + " | new-only reasons |", "|---" * (len(PAIRS) + 2) + "|"]
        for tid in h.index:
            cells = []
            for a, b, f in PAIRS:
                hv, nv = h.loc[tid, a], n.loc[tid, b]
                cells.append(f"{fmt(f, hv)} / {fmt(f, nv)}" + (" **≠**" if a == "flag" and hv != nv else ""))
            hr = set(str(h.loc[tid, "reasons"]).split("; "))
            extra = [r for r in str(n.loc[tid, "reasons"]).split("; ") if not any(k in r for k in ("availability", "trip episodes", "abnormal oil",
                                                                                                    "oil-temp model", "pump pressure", "data missing"))]
            cells.append("; ".join(extra) if extra and extra != ["no trigger"] else "-")
            L.append(f"| {tid} | " + " | ".join(cells) + " |")
        L.append("")
    out = ROOT / "reports" / "fleet_proof" / "consistency.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main(sys.argv[1:] or ["kelmarsh", "penmanshiel"])
