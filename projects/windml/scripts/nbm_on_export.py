"""Close the loop: raw export -> `windml ingest load --export` -> the ORIGINAL scripts/run_nbm_years.py -> compare.

Builds a reduced copy of a mapping (selected turbines and years), exports it into the all-years layout in a scratch
WINDML_DATA_DIR, runs the unchanged run_nbm_years.py on it and compares the residual z-scores with the reference run
in data/nbm_years (built from the original Greenbyte pipeline). Writes a short markdown result.
Usage: python scripts/nbm_on_export.py [--mapping mappings/kelmarsh_all_years.yaml] [--turbine 1] [--years 2016-2018]
"""
from __future__ import annotations
import argparse
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from windml import config as cfg  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--mapping", default=str(ROOT / "mappings" / "kelmarsh_all_years.yaml"))
    ap.add_argument("--turbine", default="1", help="turbine number in the file names")
    ap.add_argument("--years", default="2016-2018")
    ap.add_argument("--out", default=str(ROOT / "reports" / "fleet_proof" / "nbm_on_export.md"))
    a = ap.parse_args()
    y0, y1 = map(int, a.years.split("-"))
    m = yaml.safe_load(Path(a.mapping).read_text())
    farm = m["name"]
    cap = farm.capitalize()
    for part in ("scada", "status"):
        root = m[part]["files"][0]["glob"].split("/")[0]
        kind = "Turbine_Data" if part == "scada" else "Status"
        m[part]["files"] = [f"{root}/scada_{y}/{kind}_{cap}_{a.turbine}_*.csv" for y in range(y0, y1 + 1)]
    scratch = Path(tempfile.mkdtemp(prefix="windml_nbm_export_"))
    mp = scratch / "mapping.yaml"
    mp.write_text(yaml.safe_dump(m, sort_keys=False))
    env = {**os.environ, "WINDML_DATA_DIR": str(scratch), "WINDML_RAW_DIR": str(cfg.RAW_DIR)}
    t0 = time.time()
    subprocess.run([sys.executable, "-m", "windml", "ingest", "load", "-m", str(mp), "--out", str(scratch / "processed" / "all_years"),
                    "--export"], check=True, env={**env, "PYTHONPATH": str(ROOT / "src")}, cwd=ROOT)
    t1 = time.time()
    subprocess.run([sys.executable, str(ROOT / "scripts" / "run_nbm_years.py"), farm], check=True, env=env, cwd=ROOT)
    t2 = time.time()
    tid = m["scada"]["turbine_id"]["format"].format(int(a.turbine))
    new = pd.read_parquet(scratch / "nbm_years" / f"{farm}_{tid}.parquet")
    ref = pd.read_parquet(cfg.NBM_YEARS_DIR / f"{farm}_{tid}.parquet")
    ref = ref[ref["year"].between(y0, y1)]
    j = new.merge(ref, on="timestamp", suffixes=("", "_ref"))
    zc = [c for c in new.columns if c.startswith("z_")]
    rows = []
    for c in zc:
        both = j[[c, c + "_ref"]].dropna()
        scored_new, scored_ref = int(j[c].notna().sum()), int(j[c + "_ref"].notna().sum())
        if len(both) < 100:
            rows.append(f"| {c[2:]} | {scored_new:,} | {scored_ref:,} | - | - | - |")
            continue
        r = float(np.corrcoef(both[c], both[c + "_ref"])[0, 1])
        ad = (both[c] - both[c + "_ref"]).abs()
        agree = float(((both[c].abs() > 3) == (both[c + "_ref"].abs() > 3)).mean())
        rows.append(f"| {c[2:]} | {scored_new:,} | {scored_ref:,} | {r:.4f} | {float(ad.median()):.3f} | {agree:.2%} |")
    diffs = [float((j[c] - j[c + "_ref"]).abs().max()) for c in zc if j[[c, c + "_ref"]].dropna().shape[0] >= 100]
    same_n = all(int(j[c].notna().sum()) == int(j[c + "_ref"].notna().sum()) for c in zc)
    if diffs and max(diffs) < 1e-4 and same_n:
        verdict = (f"Result: identical. Every scored target has the same scored rows and a max |z| difference of {max(diffs):.1e}; "
                   "targets with 0 rows have no data in these years in either run.")
    else:
        verdict = ("Result: close but not identical. Expected sources: the export converts oil pressure per row before "
                   "interpolation (see reports/ingest/proof.md), which changes a few rows and LightGBM sub-samples.")
    md = [f"# NBM on an exported farm ({farm} {tid}, {y0}-{y1})", "",
          f"Generated by `scripts/nbm_on_export.py`: raw Greenbyte files -> `windml ingest load --export` (mapping "
          f"`{Path(a.mapping).name}` reduced to {tid}, {y0}-{y1}) -> the unchanged `scripts/run_nbm_years.py` with "
          "WINDML_DATA_DIR pointing at the export -> residual z compared with the reference run in `data/nbm_years` "
          "(built from the original Greenbyte pipeline over all years; same model, seed and rules).", "",
          f"- Export: {t1 - t0:.0f} s; NBM: {t2 - t1:.0f} s; {len(j):,} timestamps matched.",
          f"- Scored years: the export has {y0} as its only training year for {y0 + 1}, like the reference; later years "
          "train on the same prior years in both runs.", "",
          "| target | scored rows (export) | scored rows (reference) | correlation | median abs z diff | same side of 3 |",
          "|---|---|---|---|---|---|"] + rows + ["", verdict, ""]
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(md))
    print("\n".join(md))
    print(f"(scratch data left in {scratch}; delete it when done)" if os.environ.get("KEEP_SCRATCH") else "")
    if not os.environ.get("KEEP_SCRATCH"):
        import shutil
        shutil.rmtree(scratch, ignore_errors=True)


if __name__ == "__main__":
    main()
